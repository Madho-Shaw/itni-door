def pp(x): return f"{100 * x:.1f}"


def ind(x):
    """Indian digit grouping (7,42,354), as the site and report print counts."""
    s_ = f"{int(round(x)):d}"
    if len(s_) <= 3:
        return s_
    head, tail, parts = s_[:-3], s_[-3:], []
    while len(head) > 2:
        parts.insert(0, head[-2:]); head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join(parts + [tail])


