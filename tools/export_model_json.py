def lakh(x): return f"{x:.1f}"


def rs(x):
    """Rupees with Indian digit grouping (1,65,114), as the pages print them."""
    s = f"{round(x):d}"
    if len(s) <= 3:
        return s
    head, tail = s[:-3], s[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:]); head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join(parts + [tail])

