def pct(x):
    """Same rounding as the script's report (f-string .0f)."""
    return int(f"{100 * x:.0f}")


def of100(p):
    """Whole numbers that add to 100 (largest remainder), for 100-dot grids. Same rule as the game's rl_model.js."""
    keys = list(p)
    fl = {k: math.floor(p[k] * 100) for k in keys}
    rem = sorted(keys, key=lambda k: -(p[k] * 100 - fl[k]))
    i, s = 0, sum(fl.values())
    while s < 100:
        fl[rem[i % len(rem)]] += 1
        i += 1; s += 1
    return fl


