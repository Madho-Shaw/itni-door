def yml(d, ind=0):
    lines = []
    for k, v in d.items():
        if k.startswith("_"):
            lines.append(" " * ind + f"# {v}")
            continue
        if isinstance(v, dict):
            lines.append(" " * ind + f"{k}:")
            lines.extend(yml(v, ind + 2))
        else:
            s = str(v).replace('"', '\\"')
            lines.append(" " * ind + f'{k}: "{s}"')
    return lines

